const materias = [
  "Inteligência Artificial",
  "Modelagem e Desenvolvimento de Banco de Dados",
  "Programação Back-End",
  "Programação Front-End",
  "Programação Mobile",
  "Projeto Multidisciplinar em Desenvolvimento de Sistemas",
  "Versionamento de Código e Sistemas de Mensageria"
];

const activityList = document.getElementById("activityList");
const subjectFilter = document.getElementById("subjectFilter");
const semesterFilter = document.getElementById("semesterFilter");
const termFilter = document.getElementById("termFilter");

function preencherMaterias() {
  materias.forEach((materia) => {
    const option = document.createElement("option");
    option.value = materia;
    option.textContent = materia;
    subjectFilter.appendChild(option);
  });
}

function atualizarBimestres() {
  const semestre = Number(semesterFilter.value);
  const bimestres = semestre === 1 ? [1, 2] : [3, 4];
  const selecionado = Number(termFilter.value);
  termFilter.replaceChildren();

  bimestres.forEach((bimestre) => {
    const option = document.createElement("option");
    option.value = String(bimestre);
    option.textContent = `${bimestre}º Bimestre`;
    termFilter.appendChild(option);
  });

  termFilter.value = bimestres.includes(selecionado)
    ? String(selecionado)
    : String(bimestres[0]);
}

function atividadeValida(item) {
  const bimestreCorresponde =
    (Number(item.semestre) === 1 && [1, 2].includes(Number(item.bimestre))) ||
    (Number(item.semestre) === 2 && [3, 4].includes(Number(item.bimestre)));

  return materias.includes(item.materia) &&
    [1, 2].includes(Number(item.semestre)) &&
    bimestreCorresponde &&
    item.titulo &&
    item.semana;
}

function criarCartao(item) {
  const card = document.createElement("article");
  card.className = "activity-card";

  const info = document.createElement("div");
  info.className = "activity-info";

  const subject = document.createElement("div");
  subject.className = "activity-subject";
  subject.textContent = item.materia;

  const meta = document.createElement("div");
  meta.className = "activity-meta";
  meta.textContent = `${item.semana} · ${item.semestre}º semestre · ${item.bimestre}º bimestre`;

  const title = document.createElement("h3");
  title.textContent = item.titulo;

  const description = document.createElement("p");
  description.textContent = item.descricao || "Sem descrição informada.";

  info.append(subject, meta, title, description);
  card.append(info);

  const attachments = Array.isArray(item.arquivos) ? item.arquivos : (item.url ? [{ nome: "Acessar atividade", url: item.url }] : []);
  if (attachments.length) {
    const links = document.createElement("div");
    links.className = "activity-files";
    attachments.forEach((arquivo) => {
      const link = document.createElement("a");
      link.className = "activity-link";
      link.href = arquivo.url;
      link.target = "_blank";
      link.rel = "noopener noreferrer";
      link.textContent = `${arquivo.nome} ↗`;
      link.setAttribute("aria-label", `Abrir ${arquivo.nome} da atividade ${item.titulo}`);
      links.appendChild(link);
    });
    card.append(links);
  }

  return card;
}

function renderActivities() {
  const materiaSelecionada = subjectFilter.value;
  const semestre = Number(semesterFilter.value);
  const bimestre = Number(termFilter.value);

  const itens = atividades.filter((item) =>
    atividadeValida(item) &&
    (materiaSelecionada === "todas" || item.materia === materiaSelecionada) &&
    Number(item.semestre) === semestre &&
    Number(item.bimestre) === bimestre
  );

  const nomeMateria = materiaSelecionada === "todas"
    ? "TODAS AS MATÉRIAS"
    : materiaSelecionada.toLocaleUpperCase("pt-BR");

  document.getElementById("periodLabel").textContent =
    `${nomeMateria} / ${semestre}º SEMESTRE / ${bimestre}º BIMESTRE`;
  document.getElementById("activityCount").textContent =
    `${itens.length} ${itens.length === 1 ? "atividade" : "atividades"}`;

  activityList.replaceChildren();

  if (itens.length === 0) {
    const empty = document.createElement("div");
    empty.className = "empty-state";

    const icon = document.createElement("div");
    icon.className = "empty-icon";
    icon.textContent = "—";

    const heading = document.createElement("h3");
    heading.textContent = "Nenhuma atividade disponível neste período.";

    const message = document.createElement("p");
    message.textContent = "Assim que houver atividades cadastradas para esta seleção, elas aparecerão aqui.";

    empty.append(icon, heading, message);
    activityList.appendChild(empty);
    return;
  }

  itens.forEach((item) => activityList.appendChild(criarCartao(item)));
}

subjectFilter.addEventListener("change", renderActivities);
semesterFilter.addEventListener("change", () => {
  atualizarBimestres();
  renderActivities();
});
termFilter.addEventListener("change", renderActivities);

const menuToggle = document.getElementById("menuToggle");
const nav = document.getElementById("nav");

menuToggle.addEventListener("click", () => {
  const aberto = nav.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", String(aberto));
});

nav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    nav.classList.remove("open");
    menuToggle.setAttribute("aria-expanded", "false");
  });
});

preencherMaterias();
atualizarBimestres();
renderActivities();
